#!/usr/bin/env node
/**
 * Sidecar to build-exercise-references.mjs — applies the build-time distilled
 * summaries (gist / steps / cues) onto lib/exerciseReferences.ts.
 *
 * It reads the EXISTING generated map (no network, no fuzzy re-matching, no
 * image re-download) plus scripts/data/distilled-references.json, merges the
 * three optional fields per exercise, and rewrites the file with the extended
 * interface. Safe + deterministic to re-run.
 *
 * Why a sidecar: distillation is a content concern, separate from the
 * mapping/image concern in the main generator. Running this alone re-applies
 * copy edits without touching mappings. The main generator also merges the
 * same JSON when present, so a full rebuild stays consistent.
 *
 * Run from repo root:
 *   node scripts/distill-exercise-references.mjs
 */

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT_TS = join(ROOT, 'lib/exerciseReferences.ts')
const DISTILLED = join(ROOT, 'scripts/data/distilled-references.json')

const MARKER = 'export const exerciseReferences: Record<string, ExerciseReference> = '

function emitTypeScript(entries) {
  const header = `// AUTO-GENERATED by scripts/build-exercise-references.mjs — do not hand-edit.
// Re-run the script when EX changes in app/app/fitness/log/splitData.ts.
// Distilled gist/steps/cues come from scripts/distill-exercise-references.mjs.
// Source: Free Exercise DB (https://github.com/yuhonas/free-exercise-db, public domain).

export interface ExerciseReference {
  freeDbId: string
  confidence: 'high' | 'medium' | 'low'
  images: string[]
  instructions: string[]
  primaryMuscles: string[]
  equipment: string
  // Build-time distilled summary — short, phone-readable. Optional so any
  // un-distilled entry still type-checks; the card falls back to instructions.
  gist?: string
  steps?: string[]
  cues?: string[]
}

export const exerciseReferences: Record<string, ExerciseReference> = `

  const sorted = Object.fromEntries(Object.entries(entries).sort(([a], [b]) => a.localeCompare(b)))
  return header + JSON.stringify(sorted, null, 2) + '\n'
}

async function main() {
  const src = await readFile(OUTPUT_TS, 'utf-8')
  const idx = src.indexOf(MARKER)
  if (idx < 0) throw new Error(`Marker not found in ${OUTPUT_TS}`)
  const data = JSON.parse(src.slice(idx + MARKER.length).trim())
  const distilled = JSON.parse(await readFile(DISTILLED, 'utf-8'))

  let applied = 0
  const missing = []
  for (const [id, entry] of Object.entries(data)) {
    const d = distilled[id]
    if (!d) { missing.push(id); continue }
    if (typeof d.gist === 'string') entry.gist = d.gist
    if (Array.isArray(d.steps)) entry.steps = d.steps
    if (Array.isArray(d.cues)) entry.cues = d.cues
    applied++
  }

  await writeFile(OUTPUT_TS, emitTypeScript(data))

  const orphans = Object.keys(distilled).filter(id => !data[id])
  console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━')
  console.log(`Distilled fields applied : ${applied}/${Object.keys(data).length}`)
  if (missing.length) console.log(`No distilled copy for    : ${missing.join(', ')}`)
  if (orphans.length) console.log(`Distilled, no reference  : ${orphans.join(', ')}`)
  console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━')
  console.log(`Output: ${OUTPUT_TS}`)
}

main().catch(e => { console.error(e); process.exit(1) })
